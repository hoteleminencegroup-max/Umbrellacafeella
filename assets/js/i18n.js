  var current = 'en';
  var listeners = [];

  function t(key, vars) {
    var dict = I18N[current] || I18N.en;
    var str = dict[key] !== undefined ? dict[key] : (I18N.en[key] !== undefined ? I18N.en[key] : key);
    if (vars) {
      Object.keys(vars).forEach(function (k) {
        str = String(str).replace(new RegExp('\\{' + k + '\\}', 'g'), vars[k]);
      });
    }
    return str;
  }

  function setLang(code) {
    if (!I18N[code]) code = 'en';
    current = code;
    try { localStorage.setItem('uc_lang', code); } catch (e) {}
    document.documentElement.setAttribute('lang', code);
    document.documentElement.setAttribute('dir', I18N[code]._meta.dir || 'ltr');
    listeners.forEach(function (fn) { try { fn(code); } catch (e) { console.error(e); } });
  }

  function getLang() { return current; }
  function meta() { return (I18N[current] || I18N.en)._meta; }
  function available() { return Object.keys(I18N).map(function (k) { return { code: k, label: I18N[k]._meta.label, short: I18N[k]._meta.short, flag: I18N[k]._meta.flag }; }); }
  function onChange(fn) { listeners.push(fn); }

  /** Localised value from a {en,fr,ru,de} object */
  function L(obj) {
    if (obj == null) return '';
    if (typeof obj === 'string') return obj;
    return obj[current] || obj.en || Object.keys(obj).map(function (k) { return obj[k]; })[0] || '';
  }

  /** LKR money formatting */
  function money(value) {
    var v = Math.round(Number(value) || 0);
    try {
      var s = new Intl.NumberFormat(meta().locale, { maximumFractionDigits: 0 }).format(v);
      return meta().currency + ' ' + s;
    } catch (e) {
      return meta().currency + ' ' + v;
    }
  }

  function init() {
    var saved = null;
    try { saved = localStorage.getItem('uc_lang'); } catch (e) {}
    if (!saved) {
      var nav = (navigator.language || 'en').slice(0, 2).toLowerCase();
      saved = I18N[nav] ? nav : 'en';
    }
    current = I18N[saved] ? saved : 'en';
    document.documentElement.setAttribute('lang', current);
  }

